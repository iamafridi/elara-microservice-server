import { Injectable } from '@nestjs/common';
import { TypeOrmModuleOptions, TypeOrmOptionsFactory } from '@nestjs/typeorm';
import {
  User,
  Session,
  Otp,
  UserAddress,
  UserDevice,
  UserDocument,
  Merchant,
  MerchantCategory,
  MerchantHour,
  MerchantBranch,
  MerchantDocument,
  MerchantReview,
  MerchantPayout,
  Product,
  ProductCategory,
  ProductVariant,
  ProductAddon,
  Order,
  OrderItem,
  OrderStatusLog,
  Cart,
  CartItem,
  Rider,
  RiderEarning,
  RiderLocation,
  RiderZone,
  RiderWithdrawal,
  RiderDocument,
  RiderFeedVideo,
  RiderFeedLike,
  RiderFeedComment,
  RiderFollower,
  TaskerProfile,
  TaskerPortfolio,
  TaskerDocument,
  Job,
  JobCategory,
  JobQuote,
  JobAssignment,
  JobMessage,
  JobPayment,
  JobReview,
  Wallet,
  WalletTransaction,
  Transaction,
  Payout,
  Refund,
  Zone,
  ZoneModule,
  DispatchSetting,
  LandingPage,
  BlogPost,
  Faq,
  AppLink,
  PromoCode,
  Banner,
  Notification,
  NotificationToken,
  SupportTicket,
  ChatMessage,
  Review,
  RatingsSummary,
  AnalyticsEvent,
  AppSetting,
  AdminUser,
  AuditLog,
} from '../../database/src/entities';

@Injectable()
export class DatabaseConfigService implements TypeOrmOptionsFactory {
  createTypeOrmOptions(): TypeOrmModuleOptions {
    // Explicitly list all entity classes
    const entities = [
      User,
      Session,
      Otp,
      UserAddress,
      UserDevice,
      UserDocument,
      Merchant,
      MerchantCategory,
      MerchantHour,
      MerchantBranch,
      MerchantDocument,
      MerchantReview,
      MerchantPayout,
      Product,
      ProductCategory,
      ProductVariant,
      ProductAddon,
      Order,
      OrderItem,
      OrderStatusLog,
      Cart,
      CartItem,
      Rider,
      RiderEarning,
      RiderLocation,
      RiderZone,
      RiderWithdrawal,
      RiderDocument,
      RiderFeedVideo,
      RiderFeedLike,
      RiderFeedComment,
      RiderFollower,
      TaskerProfile,
      TaskerPortfolio,
      TaskerDocument,
      Job,
      JobCategory,
      JobQuote,
      JobAssignment,
      JobMessage,
      JobPayment,
      JobReview,
      Wallet,
      WalletTransaction,
      Transaction,
      Payout,
      Refund,
      Zone,
      ZoneModule,
      DispatchSetting,
      LandingPage,
      BlogPost,
      Faq,
      AppLink,
      PromoCode,
      Banner,
      Notification,
      NotificationToken,
      SupportTicket,
      ChatMessage,
      Review,
      RatingsSummary,
      AnalyticsEvent,
      AppSetting,
      AdminUser,
      AuditLog,
    ];

    // Support both DATABASE_URL and individual DB_* variables
    const baseConfig = {
      type: 'postgres' as const,
      entities,
      synchronize: false, // Disabled to prevent schema sync errors with existing data
      logging: process.env.NODE_ENV === 'development',
      ssl: false, // Disable SSL for Docker environment
      extra: {
        max: parseInt(process.env.DATABASE_POOL_SIZE || '20', 10),
      },
    };

    // Use DATABASE_URL if provided, otherwise use individual variables
    if (process.env.DATABASE_URL) {
      return {
        ...baseConfig,
        url: process.env.DATABASE_URL,
      };
    } else {
      return {
        ...baseConfig,
        host: process.env.DB_HOST || 'localhost',
        port: parseInt(process.env.DB_PORT || '5432', 10),
        username: process.env.DB_USERNAME || 'postgres',
        password: process.env.DB_PASSWORD || 'postgres',
        database: process.env.DB_NAME || 'postgres',
      };
    }
  }
}
